package dev.kairos.security.keyset;

import com.github.benmanes.caffeine.cache.Cache;
import com.github.benmanes.caffeine.cache.Caffeine;
import com.google.crypto.tink.AccessesPartialKey;
import com.google.crypto.tink.Aead;
import com.google.crypto.tink.InsecureSecretKeyAccess;
import com.google.crypto.tink.KeysetHandle;
import com.google.crypto.tink.Mac;
import com.google.crypto.tink.TinkProtoKeysetFormat;
import com.google.crypto.tink.aead.PredefinedAeadParameters;
import com.google.crypto.tink.mac.HmacKey;
import com.google.crypto.tink.mac.HmacParameters;
import com.google.crypto.tink.signature.EcdsaParameters;
import com.google.crypto.tink.util.SecretBytes;
import dev.kairos.domain.id.TeamId;
import dev.kairos.security.RandomTokens;
import dev.kairos.security.SecretValue;
import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.security.SecureRandom;
import java.time.Duration;
import java.util.Arrays;
import java.util.HexFormat;
import java.util.Objects;

/**
 * Creates, seals, rotates and opens the Tink keysets of teams and of the platform (LLD section 2.2,
 * {@code team_keysets} and {@code platform_keysets}).
 *
 * <p>Every keyset is sealed by the {@link KeyEncryptionKey} with associated data naming its owner and purpose
 * ({@code team_keysets|<teamId>|<purpose>} or {@code platform_keysets|<purpose>}), so a sealed keyset only opens for
 * the row it was written for. A keyset sealed under another KEK URI is refused before any decryption is attempted.
 *
 * <ul>
 *   <li>{@link KeyPurpose#SECRETS} and {@link KeyPurpose#OUTPUTS}: AES-256-GCM, generated by Tink.
 *   <li>{@link KeyPurpose#SIGNING}: HMAC-SHA256 with a 32-byte tag and no output prefix, so signatures are plain
 *       HMAC. The key bytes come from the injected {@link SecureRandom} because the team is shown the key once
 *       ({@code ksig_v<n>_...}). The key id inside the keyset is the version; rotation adds version {@code n + 1} as
 *       primary and keeps only the previous key, which targets may still accept for a grace period.
 *   <li>{@link PlatformKeyPurpose#JWT_SIGNING}: ECDSA P-256 with SHA-256 and IEEE P1363 signatures (the ES256 format),
 *       no output prefix.
 * </ul>
 *
 * <p>Opening a keyset costs a KEK call (a Cloud KMS round trip in production), so opened keysets are cached in memory
 * by owner, purpose and a SHA-256 of the ciphertext; a rotated keyset has new ciphertext and so a new entry. Entries
 * expire after a period without use.
 *
 * <p>Thread-safe.
 */
public final class KeysetService {

    private static final String SIGNING_KEY_PREFIX = "ksig_v";
    private static final int SIGNING_KEY_BYTES = 32;

    private final KeyEncryptionKey kek;
    private final SecureRandom random;
    private final Cache<String, KeysetHandle> opened;

    /**
     * Creates the service.
     *
     * @param kek the key encryption key
     * @param random the CSPRNG for signing key bytes
     * @param cacheExpiry how long an opened keyset stays cached without use
     * @param cacheSize the maximum number of opened keysets kept
     */
    public KeysetService(KeyEncryptionKey kek, SecureRandom random, Duration cacheExpiry, long cacheSize) {
        this.kek = Objects.requireNonNull(kek, "kek");
        this.random = Objects.requireNonNull(random, "random");
        this.opened = Caffeine.newBuilder()
                .expireAfterAccess(cacheExpiry)
                .maximumSize(cacheSize)
                .build();
    }

    /**
     * Returns the URI of the key encryption key new keysets are sealed with.
     *
     * @return the URI
     */
    public String kekUri() {
        return kek.uri();
    }

    /**
     * Creates a team's AES-256-GCM keyset.
     *
     * @param team the team
     * @param purpose {@link KeyPurpose#SECRETS} or {@link KeyPurpose#OUTPUTS}
     * @return the sealed keyset to store
     * @throws IllegalArgumentException for {@link KeyPurpose#SIGNING}; use {@link #createSigningKey(TeamId)}
     */
    public SealedKeyset createTeamKeyset(TeamId team, KeyPurpose purpose) {
        requireAeadPurpose(purpose);
        try {
            KeysetHandle handle = KeysetHandle.generateNew(PredefinedAeadParameters.AES256_GCM);
            return seal(handle, teamAssociatedData(team, purpose));
        } catch (GeneralSecurityException e) {
            throw new KeysetException("cannot create a team keyset", e);
        }
    }

    /**
     * Opens a team's AEAD keyset.
     *
     * @param team the team
     * @param purpose {@link KeyPurpose#SECRETS} or {@link KeyPurpose#OUTPUTS}
     * @param sealed the stored keyset
     * @return the AEAD
     * @throws KeysetException if the keyset does not open for this team and purpose
     */
    public TeamAead aead(TeamId team, KeyPurpose purpose, SealedKeyset sealed) {
        requireAeadPurpose(purpose);
        KeysetHandle handle = open(sealed, teamAssociatedData(team, purpose));
        try {
            return new TeamAead(team, purpose, handle.getPrimitive(TinkRuntime.configuration(), Aead.class));
        } catch (GeneralSecurityException e) {
            throw new KeysetException("the team keyset is not an AEAD keyset", e);
        }
    }

    /**
     * Creates a team's first request-signing key (version 1).
     *
     * @param team the team
     * @return the sealed keyset and the key to show once
     */
    public NewSigningKey createSigningKey(TeamId team) {
        return addSigningKey(team, KeysetHandle.newBuilder(), 1);
    }

    /**
     * Rotates a team's request-signing key: the new key (version {@code n + 1}) becomes primary, the current primary is
     * kept, and anything older is dropped.
     *
     * @param team the team
     * @param current the stored SIGNING keyset
     * @return the sealed keyset and the new key to show once
     */
    public NewSigningKey rotateSigningKey(TeamId team, SealedKeyset current) {
        KeysetHandle handle = open(current, teamAssociatedData(team, KeyPurpose.SIGNING));
        KeysetHandle.Builder builder = KeysetHandle.newBuilder(handle);
        for (int i = builder.size() - 1; i >= 0; i--) {
            if (!builder.getAt(i).isPrimary()) {
                builder.deleteAt(i);
            }
        }
        return addSigningKey(team, builder, handle.getPrimary().getId() + 1);
    }

    /**
     * Removes every non-primary request-signing key after the caller has checked the persisted overlap deadline.
     * The current version and its key bytes stay unchanged; the returned keyset is sealed for the same team.
     *
     * @param team the owning team
     * @param current the stored SIGNING keyset
     * @return a sealed keyset containing only the current primary
     * @throws KeysetException if the keyset cannot be opened or sealed
     */
    public SealedKeyset pruneSigningKeys(TeamId team, SealedKeyset current) {
        KeysetHandle handle = open(current, teamAssociatedData(team, KeyPurpose.SIGNING));
        KeysetHandle.Builder builder = KeysetHandle.newBuilder(handle);
        for (int i = builder.size() - 1; i >= 0; i--) {
            if (!builder.getAt(i).isPrimary()) {
                builder.deleteAt(i);
            }
        }
        try {
            return seal(builder.build(), teamAssociatedData(team, KeyPurpose.SIGNING));
        } catch (GeneralSecurityException e) {
            throw new KeysetException("cannot prune a signing keyset", e);
        }
    }

    /**
     * Opens a team's request-signing key.
     *
     * @param team the team
     * @param sealed the stored SIGNING keyset
     * @return the key
     * @throws KeysetException if the keyset does not open for this team
     */
    public TeamSigningKey signingKey(TeamId team, SealedKeyset sealed) {
        KeysetHandle handle = open(sealed, teamAssociatedData(team, KeyPurpose.SIGNING));
        try {
            return new TeamSigningKey(
                    team, handle.getPrimary().getId(), handle.getPrimitive(TinkRuntime.configuration(), Mac.class));
        } catch (GeneralSecurityException e) {
            throw new KeysetException("the team keyset is not a signing keyset", e);
        }
    }

    /**
     * Creates the platform's access-token signing keyset with one ECDSA P-256 key.
     *
     * @return the sealed keyset to store in {@code platform_keysets}
     */
    public SealedKeyset createJwtSigningKeyset() {
        try {
            KeysetHandle handle = KeysetHandle.newBuilder()
                    .addEntry(KeysetHandle.generateEntryFromParameters(jwtParameters())
                            .withRandomId()
                            .makePrimary())
                    .build();
            return seal(handle, platformAssociatedData(PlatformKeyPurpose.JWT_SIGNING));
        } catch (GeneralSecurityException e) {
            throw new KeysetException("cannot create the access-token signing keyset", e);
        }
    }

    /**
     * Rotates the access-token signing keyset: a new key becomes primary and the previous primary stays, so tokens it
     * signed verify until they expire. Older keys are dropped.
     *
     * @param current the stored keyset
     * @return the new sealed keyset
     */
    public SealedKeyset rotateJwtSigningKeyset(SealedKeyset current) {
        byte[] associatedData = platformAssociatedData(PlatformKeyPurpose.JWT_SIGNING);
        KeysetHandle handle = open(current, associatedData);
        KeysetHandle.Builder builder = KeysetHandle.newBuilder(handle);
        for (int i = builder.size() - 1; i >= 0; i--) {
            if (!builder.getAt(i).isPrimary()) {
                builder.deleteAt(i);
            }
        }
        try {
            builder.addEntry(KeysetHandle.generateEntryFromParameters(jwtParameters())
                    .withRandomId()
                    .makePrimary());
            return seal(builder.build(), associatedData);
        } catch (GeneralSecurityException e) {
            throw new KeysetException("cannot rotate the access-token signing keyset", e);
        }
    }

    /**
     * Opens a platform keyset.
     *
     * @param purpose the purpose
     * @param sealed the stored keyset
     * @return the keyset handle, with private keys
     * @throws KeysetException if the keyset does not open for this purpose
     */
    public KeysetHandle openPlatformKeyset(PlatformKeyPurpose purpose, SealedKeyset sealed) {
        return open(sealed, platformAssociatedData(purpose));
    }

    @AccessesPartialKey
    private NewSigningKey addSigningKey(TeamId team, KeysetHandle.Builder builder, int version) {
        byte[] key = RandomTokens.bytes(random, SIGNING_KEY_BYTES);
        try {
            HmacParameters parameters = HmacParameters.builder()
                    .setKeySizeBytes(SIGNING_KEY_BYTES)
                    .setTagSizeBytes(32)
                    .setHashType(HmacParameters.HashType.SHA256)
                    .setVariant(HmacParameters.Variant.NO_PREFIX)
                    .build();
            HmacKey hmacKey = HmacKey.builder()
                    .setParameters(parameters)
                    .setKeyBytes(SecretBytes.copyFrom(key, InsecureSecretKeyAccess.get()))
                    .build();
            builder.addEntry(
                    KeysetHandle.importKey(hmacKey).withFixedId(version).makePrimary());
            SealedKeyset sealed = seal(builder.build(), teamAssociatedData(team, KeyPurpose.SIGNING));
            SecretValue exported =
                    SecretValue.of(SIGNING_KEY_PREFIX + version + "_" + RandomTokens.encodeBase64Url(key));
            return new NewSigningKey(sealed, version, exported);
        } catch (GeneralSecurityException e) {
            throw new KeysetException("cannot create a signing key", e);
        } finally {
            Arrays.fill(key, (byte) 0);
        }
    }

    private static EcdsaParameters jwtParameters() throws GeneralSecurityException {
        return EcdsaParameters.builder()
                .setCurveType(EcdsaParameters.CurveType.NIST_P256)
                .setHashType(EcdsaParameters.HashType.SHA256)
                .setSignatureEncoding(EcdsaParameters.SignatureEncoding.IEEE_P1363)
                .setVariant(EcdsaParameters.Variant.NO_PREFIX)
                .build();
    }

    private SealedKeyset seal(KeysetHandle handle, byte[] associatedData) throws GeneralSecurityException {
        byte[] ciphertext = TinkProtoKeysetFormat.serializeEncryptedKeyset(
                handle, kek.aead(), associatedData, TinkRuntime.configuration());
        return new SealedKeyset(ciphertext, kek.uri());
    }

    private KeysetHandle open(SealedKeyset sealed, byte[] associatedData) {
        if (!sealed.kekUri().equals(kek.uri())) {
            throw new KeysetException("the keyset is sealed by another key encryption key");
        }
        byte[] ciphertext = sealed.ciphertext();
        String cacheKey = new String(associatedData, StandardCharsets.UTF_8) + "|" + sha256Hex(ciphertext);
        KeysetHandle cached = opened.getIfPresent(cacheKey);
        if (cached != null) {
            return cached;
        }
        try {
            KeysetHandle handle = TinkProtoKeysetFormat.parseEncryptedKeyset(
                    ciphertext, kek.aead(), associatedData, TinkRuntime.configuration());
            opened.put(cacheKey, handle);
            return handle;
        } catch (GeneralSecurityException e) {
            throw new KeysetException("the keyset cannot be opened", e);
        }
    }

    private static String sha256Hex(byte[] bytes) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes));
        } catch (NoSuchAlgorithmException e) {
            throw new IllegalStateException("SHA-256 is required by every JDK", e);
        }
    }

    private static void requireAeadPurpose(KeyPurpose purpose) {
        if (purpose == KeyPurpose.SIGNING) {
            throw new IllegalArgumentException("signing keysets are created with createSigningKey");
        }
    }

    static byte[] teamAssociatedData(TeamId team, KeyPurpose purpose) {
        return ("team_keysets|" + team + "|" + purpose.name()).getBytes(StandardCharsets.UTF_8);
    }

    static byte[] platformAssociatedData(PlatformKeyPurpose purpose) {
        return ("platform_keysets|" + purpose.name()).getBytes(StandardCharsets.UTF_8);
    }

    @Override
    public String toString() {
        return "KeysetService[kek=" + kek.uri() + "]";
    }
}
