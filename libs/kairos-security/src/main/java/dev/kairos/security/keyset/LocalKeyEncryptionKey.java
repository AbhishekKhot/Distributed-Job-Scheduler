package dev.kairos.security.keyset;

import com.google.crypto.tink.AccessesPartialKey;
import com.google.crypto.tink.Aead;
import com.google.crypto.tink.InsecureSecretKeyAccess;
import com.google.crypto.tink.KeysetHandle;
import com.google.crypto.tink.aead.AesGcmKey;
import com.google.crypto.tink.aead.AesGcmParameters;
import com.google.crypto.tink.util.SecretBytes;
import java.security.GeneralSecurityException;
import java.util.Arrays;
import java.util.HexFormat;
import java.util.Objects;

/**
 * The local key encryption key: AES-256-GCM under 32 random bytes from {@code KAIROS_LOCAL_KEK} (64 hex characters,
 * generated by {@code make env}).
 *
 * <p>It exists for the local stack only. {@link #forLocalProfile(String, boolean)} refuses to create it unless the
 * {@code local} Spring profile is active, so a production deployment can never fall back to a key held in an
 * environment variable.
 *
 * <p>Immutable and thread-safe. The key bytes never appear in {@link #toString()}.
 */
public final class LocalKeyEncryptionKey implements KeyEncryptionKey {

    /** The URI stored with keysets sealed by the local key. */
    public static final String URI = "local-kek://kairos";

    /** The Spring profile the local key requires. */
    public static final String PROFILE = "local";

    private static final int KEY_BYTES = 32;

    private final Aead aead;

    private LocalKeyEncryptionKey(Aead aead) {
        this.aead = aead;
    }

    /**
     * Creates the local key.
     *
     * @param hexKey the key, 64 hexadecimal characters
     * @param localProfileActive whether the {@value #PROFILE} profile is active
     * @return the key
     * @throws IllegalStateException if the {@value #PROFILE} profile is not active
     * @throws IllegalArgumentException if the key is not 64 hexadecimal characters
     */
    @AccessesPartialKey
    public static LocalKeyEncryptionKey forLocalProfile(String hexKey, boolean localProfileActive) {
        if (!localProfileActive) {
            throw new IllegalStateException(
                    "the local key encryption key is only allowed with the '" + PROFILE + "' profile");
        }
        Objects.requireNonNull(hexKey, "hexKey");
        if (hexKey.length() != KEY_BYTES * 2) {
            throw new IllegalArgumentException("the local key encryption key must be 64 hexadecimal characters");
        }
        byte[] key;
        try {
            key = HexFormat.of().parseHex(hexKey);
        } catch (IllegalArgumentException e) {
            // The message of HexFormat may quote the input; never pass it on.
            throw new IllegalArgumentException("the local key encryption key must be 64 hexadecimal characters");
        }
        try {
            AesGcmParameters parameters = AesGcmParameters.builder()
                    .setKeySizeBytes(KEY_BYTES)
                    .setIvSizeBytes(12)
                    .setTagSizeBytes(16)
                    .setVariant(AesGcmParameters.Variant.NO_PREFIX)
                    .build();
            AesGcmKey aesKey = AesGcmKey.builder()
                    .setParameters(parameters)
                    .setKeyBytes(SecretBytes.copyFrom(key, InsecureSecretKeyAccess.get()))
                    .build();
            KeysetHandle handle = KeysetHandle.newBuilder()
                    .addEntry(KeysetHandle.importKey(aesKey).withRandomId().makePrimary())
                    .build();
            return new LocalKeyEncryptionKey(handle.getPrimitive(TinkRuntime.configuration(), Aead.class));
        } catch (GeneralSecurityException e) {
            throw new IllegalStateException("cannot create the local key encryption key", e);
        } finally {
            Arrays.fill(key, (byte) 0);
        }
    }

    @Override
    public String uri() {
        return URI;
    }

    @Override
    public Aead aead() {
        return aead;
    }

    /** Leaves the key out. */
    @Override
    public String toString() {
        return "LocalKeyEncryptionKey[" + URI + "]";
    }
}
