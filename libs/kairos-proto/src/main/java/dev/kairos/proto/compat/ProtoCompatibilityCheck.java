package dev.kairos.proto.compat;

import com.google.protobuf.DescriptorProtos.FileDescriptorProto;
import com.google.protobuf.DescriptorProtos.FileDescriptorSet;
import com.google.protobuf.TextFormat;
import java.io.IOException;
import java.io.InputStream;
import java.io.PrintStream;
import java.io.Reader;
import java.io.Writer;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.NoSuchFileException;
import java.nio.file.Path;
import java.util.Comparator;
import java.util.List;

/**
 * Command-line entry point of the Protobuf compatibility check, run by the {@code
 * protoCompatibilityCheck} and {@code updateProtoBaseline} Gradle tasks of kairos-proto.
 *
 * <p>Two commands are supported:
 *
 * <ul>
 *   <li>{@code check <baseline.txtpb> <current.binpb>}: compares the committed baseline (text
 *       format) with the descriptor set protoc just wrote (binary) and exits non-zero on any
 *       breaking change;
 *   <li>{@code update <current.binpb> <baseline.txtpb>}: writes the current descriptor set as the
 *       new baseline. Run it when a version of the contracts is released.
 * </ul>
 *
 * <p>The baseline is stored without source information (comments and line numbers), so editing a
 * comment never changes it. Only the build passes paths to this class; it reads and writes nothing
 * else.
 */
public final class ProtoCompatibilityCheck {

    /** Exit status when the check passes or the baseline was written. */
    static final int OK = 0;

    /** Exit status when the current contracts break the baseline. */
    static final int INCOMPATIBLE = 1;

    /** Exit status for wrong arguments or unreadable files. */
    static final int USAGE = 2;

    private static final String HEADER = """
            # Released Kairos Protobuf contracts (kairos.v1), used by the compatibility check.
            # Generated by `make gradle ARGS=":libs:kairos-proto:updateProtoBaseline"`; do not edit.
            """;

    private ProtoCompatibilityCheck() {}

    /**
     * Runs the check from the command line and exits with its status.
     *
     * @param args the command and its two paths
     */
    public static void main(String[] args) {
        System.exit(run(args, System.out, System.err));
    }

    /**
     * Runs one command.
     *
     * @param args the command ({@code check} or {@code update}) followed by two paths
     * @param out where the result is reported
     * @param err where usage errors and breaking changes are reported
     * @return {@link #OK}, {@link #INCOMPATIBLE} or {@link #USAGE}
     */
    static int run(String[] args, PrintStream out, PrintStream err) {
        if (args.length != 3) {
            err.println("Usage: check <baseline.txtpb> <current.binpb> | update <current.binpb> <baseline.txtpb>");
            return USAGE;
        }
        try {
            return switch (args[0]) {
                case "check" -> check(Path.of(args[1]), Path.of(args[2]), out, err);
                case "update" -> update(Path.of(args[1]), Path.of(args[2]), out);
                default -> {
                    err.println("Unknown command; expected check or update");
                    yield USAGE;
                }
            };
        } catch (NoSuchFileException e) {
            err.println("File not found: " + e.getFile());
            return USAGE;
        } catch (IOException e) {
            err.println("Could not read or write a descriptor set: " + e.getMessage());
            return USAGE;
        }
    }

    private static int check(Path baselineFile, Path currentFile, PrintStream out, PrintStream err) throws IOException {
        FileDescriptorSet baseline = readText(baselineFile);
        FileDescriptorSet current = readBinary(currentFile);
        List<String> violations = ProtoCompatibility.violations(baseline, current);
        if (violations.isEmpty()) {
            out.println("Protobuf contracts are compatible with " + baselineFile.getFileName());
            return OK;
        }
        err.println("Protobuf contracts break the released baseline " + baselineFile.getFileName() + ":");
        violations.forEach(violation -> err.println("  - " + violation));
        err.println("Reserve removed field numbers and names instead of reusing them (IMPLEMENTATION_CHECKLIST"
                + " section 4.7).");
        return INCOMPATIBLE;
    }

    private static int update(Path currentFile, Path baselineFile, PrintStream out) throws IOException {
        FileDescriptorSet current = readBinary(currentFile);
        FileDescriptorSet.Builder stripped = FileDescriptorSet.newBuilder();
        current.getFileList().stream()
                .sorted(Comparator.comparing(FileDescriptorProto::getName))
                .map(file -> file.toBuilder().clearSourceCodeInfo().build())
                .forEach(stripped::addFile);
        Files.createDirectories(baselineFile.toAbsolutePath().getParent());
        try (Writer writer = Files.newBufferedWriter(baselineFile, StandardCharsets.UTF_8)) {
            writer.write(HEADER);
            TextFormat.printer().print(stripped.build(), writer);
        }
        out.println("Wrote baseline " + baselineFile.getFileName() + " with " + stripped.getFileCount() + " files");
        return OK;
    }

    static FileDescriptorSet readText(Path file) throws IOException {
        try (Reader reader = Files.newBufferedReader(file, StandardCharsets.UTF_8)) {
            FileDescriptorSet.Builder builder = FileDescriptorSet.newBuilder();
            TextFormat.getParser().merge(reader, builder);
            return builder.build();
        }
    }

    static FileDescriptorSet readBinary(Path file) throws IOException {
        try (InputStream in = Files.newInputStream(file)) {
            return FileDescriptorSet.parseFrom(in);
        }
    }
}
